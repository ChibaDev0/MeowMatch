import type { AppearanceTrait } from "./appearance";

export type SelectionGuide = { description: string; checks: string[] };

/** Always available, including when the language-model service is not configured. */
export function basicSelectionGuide(
  trait: Pick<AppearanceTrait, "key" | "partner">,
): SelectionGuide {
  const partner = trait.partner;
  switch (trait.key) {
    case "breed":
      return {
        description: `มองหาแมวที่เจ้าของระบุสายพันธุ์ว่า ${partner} และมีภาพให้ดูรูปร่าง ใบหน้า และลักษณะโดยรวมอย่างชัดเจน อย่าเลือกจากชื่อเรียกหรือสีเพียงอย่างเดียว`,
        checks: [
          "สอบถามชื่อสายพันธุ์ที่เจ้าของบันทึกไว้ และดูภาพเต็มตัวกับภาพด้านหน้า",
          "ตรวจขน สีตา และหูแยกตามเป้าหมายในช่องอื่น เพราะแมวพันธุ์เดียวกันอาจมีลักษณะต่างกัน",
        ],
      };
    case "eye":
      return {
        description: `เลือกแมวที่มองเห็น${partner}ได้ชัดจากดวงตาจริงหรือภาพระยะใกล้ในแสงธรรมชาติ ดูทั้งสองข้าง ไม่อาศัยภาพที่เปิดแฟลชหรือแต่งสี`,
        checks: [
          partner === "ตาสองสี"
            ? "ดูให้เห็นว่าดวงตาซ้ายและขวามีสีต่างกัน"
            : "ดูว่าสีของดวงตาทั้งสองข้างตรงกับสีที่ต้องการ",
          "ขอภาพที่สีไม่เพี้ยน และสอบถามว่าสีตาปัจจุบันเหมือนในภาพหรือไม่",
        ],
      };
    case "coat":
      return {
        description:
          partner === "ขนสั้น"
            ? "เลือกแมวที่ขนตามลำตัวสั้นแนบรูปร่าง เห็นแนวลำตัวชัด ดูขนบริเวณคอ ท้อง และหางร่วมด้วย"
            : partner === "ขนยาว"
              ? "เลือกแมวที่มีขนยาวเห็นได้ชัดตามลำตัว โดยดูบริเวณคอ ท้อง และหางประกอบ ไม่ตัดสินจากความฟูของภาพด้านหน้าอย่างเดียว"
              : partner === "ไม่มีขน"
                ? "เลือกแมวที่มองเห็นผิวหนังเป็นส่วนใหญ่และไม่มีขนปกคลุมแบบขนสั้นหรือขนยาว ดูภาพหลายมุมเพื่อแยกจากแมวที่เพิ่งโกนขน"
                : `เลือกแมวที่มีลักษณะขน ${partner} และดูภาพเต็มตัวเพื่อเทียบความยาวกับความหนาของขน`,
        checks: ["ดูภาพด้านข้างและหางในสภาพขนปกติ", "สอบถามว่ามีการตัดหรือโกนขนก่อนถ่ายภาพหรือไม่"],
      };
    case "ear":
      return {
        description:
          partner === "หูตั้ง"
            ? "เลือกแมวที่ใบหูทั้งสองข้างตั้งขึ้นตามธรรมชาติ เห็นรูปทรงหูชัดในภาพหน้าตรงและด้านข้าง"
            : "เลือกแมวที่ใบหูพับไปด้านหน้าให้เห็นชัดทั้งสองข้าง โดยดูท่าหูขณะผ่อนคลาย ไม่ใช่ขณะลู่หูชั่วคราว",
        checks: [
          "ดูรูปทรงหูจากหลายมุม ไม่ใช้ภาพมุมเดียวตัดสิน",
          "หากแมวตั้งต้นหูพับ ให้เลือกคู่หูตั้งตามคำแนะนำของระบบ",
        ],
      };
  }
}
